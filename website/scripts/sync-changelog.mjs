// Generates src/pages/changelog.md from the package's CHANGELOG.md, adding
// release dates (from git tags) and links to pub.dev and GitHub diffs.
import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(site, '..');
const repo = 'https://github.com/thanhhaidev/flutter_date_formatter';
const pub = 'https://pub.dev/packages/flutter_date_formatter';

const source = readFileSync(join(root, 'CHANGELOG.md'), 'utf8');

/** The tag date as YYYY-MM-DD, or null when the tag is unknown (shallow clone). */
function tagDate(tag) {
  try {
    // The tagger date for annotated tags, the commit date for lightweight ones.
    return execFileSync('git', ['for-each-ref', '--format=%(creatordate:short)', `refs/tags/${tag}`], {
      cwd: root,
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .toString()
      .trim() || null;
  } catch {
    return null;
  }
}

function longDate(iso) {
  return new Date(`${iso}T00:00:00Z`).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    timeZone: 'UTC',
  });
}

/** Escapes MDX syntax (`<`, `{`, `}`) outside inline code and code blocks. */
function escapeMdx(markdown) {
  let inFence = false;
  return markdown
    .split('\n')
    .map((line) => {
      if (/^\s*```/.test(line)) {
        inFence = !inFence;
        return line;
      }
      if (inFence) return line;
      return line
        .split(/(`[^`]*`)/)
        .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/[{}]/g, (c) => `\\${c}`)))
        .join('');
    })
    .join('\n');
}

// Split into "## <version>" sections; anything before the first one is dropped.
const sections = source.split(/^## +/m).slice(1).map((chunk) => {
  const newline = chunk.indexOf('\n');
  return {
    name: chunk.slice(0, newline === -1 ? undefined : newline).trim(),
    body: newline === -1 ? '' : chunk.slice(newline + 1).trim(),
  };
});

const versions = sections.filter((s) => /^\d/.test(s.name)).map((s) => s.name);
const latestReleased = versions.find((v) => tagDate(`v${v}`));

const out = [
  '---',
  'title: Changelog',
  'description: Release notes for every version of flutter_date_formatter.',
  'wrapperClassName: changelog-page',
  '---',
  '',
  '{/* Generated by scripts/sync-changelog.mjs from CHANGELOG.md. Do not edit. */}',
  '',
  '# Changelog',
  '',
  `Release notes for every version of \`flutter_date_formatter\`, from [CHANGELOG.md](${repo}/blob/main/CHANGELOG.md). Versions follow [pub.dev](${pub}/versions).`,
  '',
];

sections.forEach(({name, body}, index) => {
  const isVersion = /^\d/.test(name);
  const previous = isVersion ? versions[versions.indexOf(name) + 1] : versions[0];
  const meta = [];

  if (isVersion) {
    const date = tagDate(`v${name}`);
    if (date) {
      meta.push(`Released ${longDate(date)}`);
      if (name === latestReleased) meta.push('**Latest**');
      meta.push(`[pub.dev](${pub}/versions/${name})`);
      if (previous) meta.push(`[Diff](${repo}/compare/v${previous}...v${name})`);
    } else {
      // Version bumped but not tagged yet.
      meta.push('Release pending');
      if (previous) meta.push(`[Changes since v${previous}](${repo}/compare/v${previous}...main)`);
    }
  } else {
    meta.push('Not published yet');
    if (previous) meta.push(`[Changes since v${previous}](${repo}/compare/v${previous}...main)`);
  }

  // "### **Added**:" -> "### Added"
  const cleaned = escapeMdx(body).replace(/^(#{3,6}) +\*\*(.+?)\*\*:?\s*$/gm, '$1 $2').replace(/^(#{3,6}) +(.+?):\s*$/gm, '$1 $2');

  out.push(`## ${isVersion ? `v${name}` : name}`, '', `<p className="release-meta">${meta.join(' · ').replace(/\*\*(.+?)\*\*/g, '<span className="release-latest">$1</span>').replace(/\[(.+?)\]\((.+?)\)/g, '<a href="$2">$1</a>')}</p>`, '', cleaned, '');
});

writeFileSync(join(site, 'src/pages/changelog.md'), `${out.join('\n').trim()}\n`);
console.log(`changelog: ${sections.length} sections`);
